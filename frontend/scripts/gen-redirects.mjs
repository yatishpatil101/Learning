/**
 * Emits `dist/_redirects` after a build.
 *
 * ### Why this is generated rather than committed
 *
 * The app is designed to be **same-origin with its API**: `services/config.js` defaults `API_BASE`
 * to the relative `/api`, and in dev the Vite proxy forwards it to the backend with the path
 * intact. Production had no equivalent, which left exactly one deployable shape — a static site
 * calling an absolute `VITE_API_BASE` on another host — and that shape is broken three ways at
 * once: `connect-src 'self'` blocks the call before it leaves the browser; CORS has to be widened;
 * and if the UI sits on its own registrable domain (`*.netlify.app` is a Public Suffix List entry)
 * the `SameSite=Lax` refresh cookie is silently dropped, so every session dies fifteen minutes
 * after login. `CookieDeliveryCheck` on the backend refuses to boot into that topology.
 *
 * A host-level `/api/*` proxy restores the invariant the rest of the codebase already assumes:
 * one origin, no CORS, no CSP change, no cookie concessions. The proxy *target*, though, is a
 * deployment-time fact — which backend, which environment — and there is no honest default for it.
 * Netlify does not interpolate environment variables inside `netlify.toml`, so the rule cannot live
 * there and stay configurable. `_redirects` is a plain text file in the publish directory, read by
 * both Netlify and Cloudflare Pages, so generating it keeps the target in the environment and the
 * config portable off Netlify.
 *
 * ### Why this file owns the proxy, and `netlify.toml` still owns a fallback
 *
 * When both files declare redirects, **`_redirects` is matched first, then `netlify.toml`** (Netlify
 * docs, *Rule processing order*). That ordering is the whole reason the proxy can live here: the
 * generated `/api/*` rule is reached before any rule in the toml, so the SPA fallback cannot shadow
 * it. The toml keeps its own `/* -> /index.html` as a safety net for the case this script does not
 * run at all — a build command that bypasses npm scripts, say — because without it a missing
 * `_redirects` is a site-wide 404 on every deep link, with nothing anywhere saying why.
 *
 * Runs as part of `build` rather than as a `postbuild` hook, and writes into `dist/`, which is
 * generated and git-ignored, so a build never dirties the source tree. `postbuild` is an npm
 * lifecycle convention: pnpm does not run it by default and `npx vite build` skips it entirely, and
 * the failure mode of it being skipped is every API call quietly resolving to the HTML shell.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const dist = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist');

// Origin only — scheme and host, no path and no trailing slash. The backend serves under
// `server.servlet.context-path=/api`, so the `/api` prefix belongs to the *path* the browser
// already wrote and is forwarded verbatim below. Folding it into the origin here would produce
// `https://host/api/api/auth/login`, a 404 that reads like a missing endpoint.
const raw = (process.env.API_ORIGIN || '').trim().replace(/\/+$/, '');

const lines = ['# Generated by scripts/gen-redirects.mjs — edit that, not this.'];

if (!raw) {
  // Unset is correct locally — the Vite dev server proxies /api itself, and `check:size` builds
  // with no backend in mind. On a deploy it is not merely incomplete, it is silent: /api/* falls
  // through to the SPA fallback and answers **200 with the HTML shell**, which `http.js` treats as
  // success. `unwrapPage` then reports `{ items: [], total: 0 }`, so every catalogue renders an
  // affirmative "no results" and `getMe` stores a truthy garbage user. Nothing errors anywhere.
  // So refuse on the one signal that distinguishes the two: Netlify sets NETLIFY=true in every
  // build. A host that sets no such variable falls back to the warning, which is the honest
  // limit of what can be detected here.
  const message =
    'API_ORIGIN is unset, so no /api proxy can be written. Set it to the backend origin, '
    + 'e.g. API_ORIGIN=https://api.punenest.in';
  if (process.env.NETLIFY) {
    throw new Error(`[redirects] ${message} — refusing to publish a build whose every API call `
      + 'would resolve to index.html with a 200.');
  }
  console.warn(`[redirects] ${message} (local build — continuing without it).`);
} else if (!/^https:\/\/[A-Za-z0-9.-]+(?::\d+)?$/.test(raw)) {
  // Refuse rather than emit a rule that half-works. A path or query in the origin silently
  // changes what every API call resolves to; plain http would put the refresh cookie — a 30-day
  // credential — on the wire in clear, which application-prod.properties hardcodes
  // `refresh-cookie.secure=true` specifically to prevent; and the host charset is pinned because
  // `_redirects` is whitespace-delimited and line-oriented, so a value containing a space mangles
  // the rule and one containing a newline appends a redirect of the attacker's choosing.
  throw new Error(
    `[redirects] API_ORIGIN="${raw}" is not a bare https origin. Expected scheme + host (+ optional `
      + 'port) only, e.g. https://api.punenest.in — no path, no trailing slash, no http.',
  );
} else {
  // `200!` forces the proxy even where a matching static asset exists, so a stray file under
  // /api in the bundle cannot shadow the API.
  lines.push(`/api/*  ${raw}/api/:splat  200!`);
}

lines.push('/*  /index.html  200', '');

writeFileSync(join(dist, '_redirects'), lines.join('\n'), 'utf8');
console.log(`[redirects] wrote dist/_redirects${raw ? ` (proxying /api to ${raw})` : ''}`);
